--
--   * No vendor adapter, and no columns anticipating one. ADR-007 took the same position for
--     telematics: the port is worth having before the vendor, the vendor is not worth guessing.
--     A real router changes RoutingProviderAdapter and writes a different `provider` value; it
--     needs nothing added here.
--   * No geometry column. The question this table answers is "how far", which is a scalar keyed on
--     two points, not a spatial query. PostGIS earns its place where the question is genuinely
--     spatial - containment, for the geofences of JOB 10 - and adding a geography column here to
--     look modern would cost an index nothing reads.
--   * No route polyline. Drawing the road on a map is a display feature that would multiply this
--     table's size by three orders of magnitude, and nothing in the product asks for it yet.
--   * No traffic or time-of-day dimension. Two speed bands is the least detail that avoids lying
--     about urban round trips; a time-of-day model without a provider behind it would be inventing
--     precision.
